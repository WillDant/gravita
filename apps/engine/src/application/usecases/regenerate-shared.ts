import { normalizePath } from "@gravita/core";
import type { SquadPlan } from "@gravita/protocol";
import {
  basenameOf,
  dirnameOf,
  LOCKFILE_COMMANDS,
  type LockfileCommand,
  MANIFEST_FILES,
} from "../../domain/squad-workspace";
import type { CheckRunner } from "../ports/check-runner";
import type { GitWorkspace } from "../ports/git-workspace";

export const REGENERATE_MESSAGE = "Gravita: regenerate lockfile";
const REGENERATE_TIMEOUT_MS = 5 * 60_000;

export interface RegenerateSharedParams {
  plan: SquadPlan;
  /** The integration worktree. */
  worktree: string;
  /** Files the merge changed; when given and no manifest is among them, nothing runs. */
  changed?: readonly string[];
}

export interface LockfileRegeneration {
  lockfile: string;
  status: "regenerated" | "unchanged" | "skipped" | "failed";
  note?: string;
}

export interface RegenerateSharedResult {
  lockfiles: LockfileRegeneration[];
  /** Gravita's lockfile commit, or null when nothing changed. */
  sha: string | null;
}

/**
 * Shared files are Gravita's: roles never merge them as text. After a merge, each shared
 * lockfile is regenerated by its package manager (lockfile only, no install scripts) in the
 * integration worktree and committed as Gravita. A manager that isn't installed is skipped.
 */
export class RegenerateShared {
  constructor(
    private readonly d: {
      git: GitWorkspace;
      runner: CheckRunner;
      /** Lockfile name → command; tests swap in fakes. */
      commands?: Readonly<Record<string, LockfileCommand>>;
      timeoutMs?: number;
    },
  ) {}

  async execute(p: RegenerateSharedParams): Promise<RegenerateSharedResult> {
    const commands = this.d.commands ?? LOCKFILE_COMMANDS;
    const lockfiles = p.plan.shared.paths
      .map(normalizePath)
      .filter((path) => Object.hasOwn(commands, basenameOf(path)));
    if (!lockfiles.length) return { lockfiles: [], sha: null };
    if (p.changed && !p.changed.some((f) => MANIFEST_FILES.has(basenameOf(f))))
      return {
        lockfiles: lockfiles.map((lockfile) => ({
          lockfile,
          status: "skipped",
          note: "no manifest changed",
        })),
        sha: null,
      };

    const results: LockfileRegeneration[] = [];
    const ran: string[] = [];
    for (const lockfile of lockfiles) {
      const command = commands[basenameOf(lockfile)];
      if (!command) continue;
      const o = await this.d.runner.run({
        argv: command.argv,
        root: p.worktree,
        cwd: dirnameOf(lockfile),
        timeoutMs: this.d.timeoutMs ?? REGENERATE_TIMEOUT_MS,
      });
      if (o.missing) {
        results.push({ lockfile, status: "skipped", note: `${command.argv[0]} is not installed` });
      } else if (!o.ok) {
        results.push({ lockfile, status: "failed", note: o.output.slice(-2_000) });
      } else {
        results.push({ lockfile, status: "unchanged" });
        ran.push(lockfile);
      }
    }

    const sha = ran.length
      ? await this.d.git.commitAll(p.worktree, { message: REGENERATE_MESSAGE, paths: ran })
      : null;
    if (sha) {
      const changed = new Set(await this.d.git.changedFiles(p.worktree, `${sha}~1`));
      for (const r of results) if (changed.has(r.lockfile)) r.status = "regenerated";
    }
    return { lockfiles: results, sha };
  }
}
